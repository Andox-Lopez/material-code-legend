# 两地共用但与大陆写法不同的词（同时挂在 hk / tw 下）
SHARED = {
    "亚克力板": "亞加力板", "灯片": "膠片",
}


def _to_trad(s, region):
    """简繁字形转换：优先 zhconv（区分港/台用词），否则用逐字表。"""
    if zhconv is not None:
        return zhconv.convert(s, "zh-tw" if region == "tw" else "zh-hk")
    return "".join(CHAR_MAP.get(ch, ch) for ch in s)


def to_hans(text, region=""):
    """简体化：用于内地 / 日本 / 韩国等非繁体地区的中文资料条目。"""
    if not text:
        return text
    if zhconv is not None:
        return zhconv.convert(text, "zh-cn")
    return text


def to_hant(text, region="hk"):
    """把简体文本转为该地区惯用的繁体文本。"""
    if not text:
        return text
    # 1) 先套地区惯用词（键为简体，避免与字形转换抢先后）
    s = text
    table = dict(SHARED)
    table.update(IDIOM.get(region, {}))
    for simp, trad in sorted(table.items(), key=lambda kv: -len(kv[0])):
        if simp in s:
            s = s.replace(simp, trad)
    # 2) 再做简繁字形转换
    return _to_trad(s, region)
